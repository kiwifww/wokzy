export function extractSteps(blocks){
 let start=blocks.findIndex(b=>b.type==='heading'&&b.text==='操作');
 if(start<0){const first=blocks.findIndex(b=>b.type==='list'&&b.ordered);if(first>=0){start=first-1;while(start>=0&&blocks[start].type!=='heading')start--;}}
 if(start<0)return [];
 const steps=[];let section='操作';
 for(const block of blocks.slice(start+1)){
  if(block.type==='heading'){if(/^(附加内容|参考资料|备注说明|营养成分)$/.test(block.text))break;section=block.text;continue;}
  const content=block.type==='list'?block.items:block.type==='paragraph'?[block.text]:[];
  for(const text of content)if(text.trim())steps.push({title:section==='操作'?`第 ${steps.length+1} 步`:section,text,tip:''});
 }
 return steps;
}
