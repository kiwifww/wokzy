export function parseCSV(text){
 const rows=[];let row=[],cell='',quoted=false;
 for(let n=0;n<text.length;n++){const c=text[n];if(c==='"'){if(quoted&&text[n+1]==='"'){cell+='"';n++;}else quoted=!quoted;}else if(c===','&&!quoted){row.push(cell);cell='';}else if(c==='\n'&&!quoted){row.push(cell.replace(/\r$/,''));if(row.some(Boolean))rows.push(row);row=[];cell='';}else cell+=c;}
 if(quoted)throw Error('Unclosed CSV quote');if(cell||row.length){row.push(cell.replace(/\r$/,''));if(row.some(Boolean))rows.push(row);}const [headers,...values]=rows;return values.map(values=>Object.fromEntries(headers.map((key,i)=>[key.replace(/^\uFEFF/,''),values[i]||''])));
}
